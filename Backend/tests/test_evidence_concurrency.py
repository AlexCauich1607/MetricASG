import uuid
from concurrent.futures import ThreadPoolExecutor
from threading import Barrier

from fastapi import HTTPException
from sqlalchemy.orm import sessionmaker

from app.models.indicator_answer_model import IndicatorAnswer
from app.core.roles import UserRole
from app.models.ambit_model import Ambit
from app.models.evaluation_evidence_model import (
    EvaluationEvidence,
    EvidenceType,
)
from app.models.evaluation_indicator_response_model import (
    EvaluationIndicatorResponse,
)
from app.models.evaluation_model import Evaluation, EvaluationStatus
from app.models.indicator_model import Indicator
from app.models.maturity_level_model import MaturityLevel
from app.models.methodology_model import Methodology
from app.models.user_model import User
from app.models.evaluation_evidence_request import EvidenceCreateRequest
from app.services.evidence_service import EvidenceService
from tests.conftest import engine


SessionLocal = sessionmaker(
    bind=engine,
    autoflush=False,
    autocommit=False,
)



def test_concurrent_evidence_creation_respects_limit():
    unique_id = uuid.uuid4().hex
    ids = {}
    barrier = Barrier(2)

    try:
        # Prepare committed data visible to both sessions.
        with SessionLocal.begin() as db:
            methodology = Methodology(
                name=f"Concurrency Test {unique_id}",
                version="TEST-1",
                is_active=False,
            )
            db.add(methodology)
            db.flush()

            ambit = Ambit(
                name="Test ambit",
                description="",
                letter="A",
                color="#37AB48",
                is_removable=False,
                methodology_id=methodology.id,
            )
            db.add(ambit)
            db.flush()

            maturity = MaturityLevel(
                name="Test maturity",
                value=6,
                description="",
                min_score=0,
                max_score=10,
                color="#37AB48",
                is_removable=False,
                methodology_id=methodology.id,
            )
            db.add(maturity)
            db.flush()

            indicator = Indicator(
                ambit_id=ambit.id,
                question="Concurrency test indicator",
            )
            db.add(indicator)
            db.flush()

            user = User(
                name="Concurrency",
                lastname="Test",
                position="Tester",
                company_name="Concurrency Test Company",
                email=f"concurrency-{unique_id}@test.local",
                phone="9999999999",
                password="test-password",
                role=UserRole.USER,
                active=True,
            )
            db.add(user)
            db.flush()

            evaluation = Evaluation(
                user_id=user.id,
                methodology_id=methodology.id,
                status=EvaluationStatus.DRAFT,
            )
            db.add(evaluation)
            db.flush()

            # IndicatorAnswer is generated by Indicator.after_insert.
            answer = next(
                answer
                for answer in indicator.answers
                if answer.maturity_level_id == maturity.id
            )

            db.add(
                EvaluationIndicatorResponse(
                    evaluation_id=evaluation.id,
                    indicator_id=indicator.id,
                    indicator_answer_id=answer.id,
                    maturity_level_id=maturity.id,
                    score=maturity.value,
                )
            )

            for index in range(4):
                db.add(
                    EvaluationEvidence(
                        evaluation_id=evaluation.id,
                        indicator_id=indicator.id,
                        user_id=user.id,
                        type=EvidenceType.COMMENT,
                        content=f"Initial evidence {index + 1}",
                    )
                )

            ids = {
                "methodology_id": methodology.id,
                "user_id": user.id,
                "evaluation_id": evaluation.id,
                "indicator_id": indicator.id,
            }

        def create_evidence(index):
            with SessionLocal() as db:
                payload = EvidenceCreateRequest(
                    indicator_id=ids["indicator_id"],
                    type="COMMENT",
                    content=f"Concurrent evidence {index}",
                )

                barrier.wait(timeout=10)

                try:
                    EvidenceService(db).create_evidence(
                        evaluation_id=ids["evaluation_id"],
                        user_id=ids["user_id"],
                        payload=payload,
                    )
                    return 201
                except HTTPException as exc:
                    return exc.status_code

        with ThreadPoolExecutor(max_workers=2) as executor:
            futures = [
                executor.submit(create_evidence, index)
                for index in range(2)
            ]

            results = [future.result(timeout=15) for future in futures]

        assert sorted(results) == [201, 409]

        with SessionLocal() as db:
            count = (
                db.query(EvaluationEvidence)
                .filter(
                    EvaluationEvidence.evaluation_id
                    == ids["evaluation_id"],
                    EvaluationEvidence.indicator_id
                    == ids["indicator_id"],
                )
                .count()
            )

            assert count == 5

    finally:
        if ids:
            with SessionLocal.begin() as db:
                db.query(EvaluationEvidence).filter(
                    EvaluationEvidence.evaluation_id
                    == ids["evaluation_id"]
                ).delete(synchronize_session=False)

                db.query(EvaluationIndicatorResponse).filter(
                    EvaluationIndicatorResponse.evaluation_id
                    == ids["evaluation_id"]
                ).delete(synchronize_session=False)

                db.query(Evaluation).filter(
                    Evaluation.id == ids["evaluation_id"]
                ).delete(synchronize_session=False)

                db.query(IndicatorAnswer).filter(
                    IndicatorAnswer.indicator_id
                    == ids["indicator_id"]
                ).delete(synchronize_session=False)

                db.query(Indicator).filter(
                    Indicator.id == ids["indicator_id"]
                ).delete(synchronize_session=False)

                db.query(Ambit).filter(
                    Ambit.methodology_id == ids["methodology_id"]
                ).delete(synchronize_session=False)

                db.query(MaturityLevel).filter(
                    MaturityLevel.methodology_id
                    == ids["methodology_id"]
                ).delete(synchronize_session=False)

                db.query(User).filter(
                    User.id == ids["user_id"]
                ).delete(synchronize_session=False)

                db.query(Methodology).filter(
                    Methodology.id == ids["methodology_id"]
                ).delete(synchronize_session=False)
